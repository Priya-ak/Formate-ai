const DICTS: Record<LangCode, Dict> = { en, ta, hi, te, kn, ml, bn, mr };

export interface Translated { text: string; lang: LangCode; fallback: boolean }

function fmt(s: string, vars: Record<string, string | number> = {}): string {
  return s.replace(/\{(\w+)\}/g, (_, k) => (vars[k] !== undefined ? String(vars[k]) : `{${k}}`));
}

/** Translate with English fallback. `lang` in the result is the language the text is actually in. */
export function tx(lang: LangCode, key: string, vars?: Record<string, string | number>): Translated {
  const d = DICTS[lang];
  if (d && d[key]) return { text: fmt(d[key], vars), lang, fallback: false };
  return { text: fmt(en[key] ?? key, vars), lang: 'en', fallback: lang !== 'en' };
}

export const t = (lang: LangCode, key: string, vars?: Record<string, string | number>) => tx(lang, key, vars).text;

export function hasKey(lang: LangCode, key: string): boolean {
  return !!DICTS[lang]?.[key];
}
